const fs = require("fs");
const path = require("path");

const rootDir = path.resolve(__dirname, "..");
const docsDir = path.join(rootDir, "docs");
const outputFile = path.join(rootDir, "assets/js/tag-index.js");
const includeDirs = [
  path.join(docsDir, "halls"),
  path.join(docsDir, "theory"),
  path.join(docsDir, "guid")
];

function walk(dir) {
  if (!fs.existsSync(dir)) return [];

  return fs.readdirSync(dir, { withFileTypes: true }).flatMap(entry => {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) return walk(fullPath);
    if (entry.isFile() && entry.name.endsWith(".md")) return [fullPath];
    return [];
  });
}

function stripCodeBlocks(text) {
  return text.replace(/```[\s\S]*?```/g, "");
}

function normalizeTag(tag) {
  return String(tag || "")
    .replace(/^#/, "")
    .replace(/\s+/g, " ")
    .trim();
}

function parseTags(text) {
  const cleanText = stripCodeBlocks(text);
  const tags = [];
  const pattern = /data-tags\s*=\s*["']([^"']+)["']/g;
  let match;

  while ((match = pattern.exec(cleanText)) !== null) {
    tags.push(...match[1].split(/[,|\n]/).map(normalizeTag).filter(Boolean));
  }

  return Array.from(new Set(tags));
}

function parseTitle(text, filePath) {
  const htmlTitle = text.match(/<h1[^>]*>(.*?)<\/h1>/i);
  if (htmlTitle) return htmlTitle[1].replace(/<[^>]+>/g, "").trim();

  const mdTitle = text.match(/^#\s+(.+)$/m);
  if (mdTitle) return mdTitle[1].trim();

  return path.basename(filePath, ".md");
}

function getDocType(filePath) {
  const relativePath = path.relative(docsDir, filePath);

  if (relativePath.startsWith(`halls${path.sep}`)) return "exhibit";
  if (relativePath.startsWith(`theory${path.sep}`)) return "theory";
  if (relativePath.startsWith(`guid${path.sep}`)) return "guide";
  return "document";
}

function makeRoute(filePath) {
  const relativePath = path.relative(rootDir, filePath).replace(/\\/g, "/");
  return `/${relativePath.replace(/\.md$/, "")}`;
}

function buildTagIndex() {
  const tagIndex = {};
  const files = includeDirs.flatMap(walk).sort();

  files.forEach(filePath => {
    const text = fs.readFileSync(filePath, "utf8");
    const tags = parseTags(text);
    if (!tags.length) return;

    const item = {
      title: parseTitle(text, filePath),
      path: makeRoute(filePath),
      type: getDocType(filePath)
    };

    tags.forEach(tag => {
      if (!tagIndex[tag]) tagIndex[tag] = [];
      tagIndex[tag].push(item);
    });
  });

  Object.keys(tagIndex).forEach(tag => {
    tagIndex[tag].sort((a, b) => a.title.localeCompare(b.title, "ko"));
  });

  return tagIndex;
}

const tagIndex = buildTagIndex();
const output = `// This file is generated by scripts/generate-tag-index.js.\n` +
  `// Do not edit it manually. Add data-tags to md files, then regenerate.\n` +
  `window.tagIndex = ${JSON.stringify(tagIndex, null, 2)};\n`;

fs.writeFileSync(outputFile, output);
console.log(`Generated ${path.relative(rootDir, outputFile)} with ${Object.keys(tagIndex).length} tags.`);
