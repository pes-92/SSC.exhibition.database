const fs = require("fs");
const path = require("path");

const rootDir = path.resolve(__dirname, "..");
const docsDir = path.join(rootDir, "docs");
const outputFile = path.join(rootDir, "assets/js/search-index.js");

const roleOrder = {
  public: 0,
  volunteer: 1,
  ssc: 2,
  admin: 3
};

function walk(dir) {
  if (!fs.existsSync(dir)) return [];

  return fs.readdirSync(dir, { withFileTypes: true }).flatMap(entry => {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) return walk(fullPath);
    if (entry.isFile() && entry.name.endsWith(".md")) return [fullPath];
    return [];
  });
}

function stripCodeBlocks(text) {
  return text.replace(/```[\s\S]*?```/g, "");
}

function stripMarkup(text) {
  return text
    .replace(/<!--[\s\S]*?-->/g, " ")
    .replace(/<script[\s\S]*?<\/script>/gi, " ")
    .replace(/<style[\s\S]*?<\/style>/gi, " ")
    .replace(/<[^>]+>/g, " ")
    .replace(/!\[[^\]]*]\([^)]+\)/g, " ")
    .replace(/\[([^\]]+)]\([^)]+\)/g, "$1")
    .replace(/[#>*_`|[\](){}:-]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function normalizeTag(tag) {
  return String(tag || "")
    .replace(/^#/, "")
    .replace(/\s+/g, " ")
    .trim();
}

function parseTitle(text, filePath) {
  const htmlTitle = text.match(/<h1[^>]*>(.*?)<\/h1>/i);
  if (htmlTitle) return stripMarkup(htmlTitle[1]);

  const mdTitle = text.match(/^#\s+(.+)$/m);
  if (mdTitle) return mdTitle[1].trim();

  return path.basename(filePath, ".md");
}

function getDocType(filePath) {
  const relativePath = path.relative(docsDir, filePath);

  if (relativePath.startsWith(`halls${path.sep}`)) return "exhibit";
  if (relativePath.startsWith(`theory${path.sep}`)) return "theory";
  if (relativePath.startsWith(`guid${path.sep}`)) return "guide";
  if (relativePath.startsWith(`school_curriculum${path.sep}`)) return "curriculum";
  return "document";
}

function makeRoute(filePath) {
  const relativePath = path.relative(rootDir, filePath).replace(/\\/g, "/");
  return `#/${relativePath.replace(/\.md$/, "")}`;
}

function getRoleFromClass(classValue) {
  if (/\badmin-only\b/.test(classValue)) return "admin";
  if (/\bssc-only\b/.test(classValue)) return "ssc";
  if (/\bvolunteer\b/.test(classValue)) return "volunteer";
  if (/\blogged-out-only\b/.test(classValue)) return "public";
  return null;
}

function getCurrentRole(stack) {
  for (let i = stack.length - 1; i >= 0; i -= 1) {
    if (stack[i]) return stack[i];
  }
  return "public";
}

function parseVisibleParts(text) {
  const cleanText = stripCodeBlocks(text);
  const parts = {
    public: [],
    volunteer: [],
    ssc: [],
    admin: []
  };
  const tags = [];
  const stack = [];

  cleanText.split(/\r?\n/).forEach(line => {
    const openDivs = [...line.matchAll(/<div\b([^>]*)>/gi)];
    openDivs.forEach(match => {
      const classMatch = match[1].match(/\bclass\s*=\s*["']([^"']+)["']/i);
      const role = classMatch ? getRoleFromClass(classMatch[1]) : null;
      stack.push(role || getCurrentRole(stack));
    });

    const role = getCurrentRole(stack);
    const tagAttrPattern = /data-tags\s*=\s*["']([^"']+)["']/gi;
    let tagAttrMatch;
    while ((tagAttrMatch = tagAttrPattern.exec(line)) !== null) {
      tagAttrMatch[1].split(/[,|\n]/).map(normalizeTag).filter(Boolean).forEach(tag => {
        tags.push({ tag, role });
      });
    }

    const textTags = line.match(/#[0-9A-Za-z가-힣_ -]+/g) || [];
    textTags.map(normalizeTag).filter(Boolean).forEach(tag => {
      tags.push({ tag, role });
    });

    const plain = stripMarkup(line);
    if (plain) parts[role].push(plain);

    const closeCount = (line.match(/<\/div>/gi) || []).length;
    for (let i = 0; i < closeCount; i += 1) {
      if (stack.length) stack.pop();
    }
  });

  return {
    segments: Object.entries(parts)
      .filter(([, values]) => values.length)
      .map(([role, values]) => ({
        role,
        text: values.join(" ")
      })),
    tags: Array.from(
      new Map(tags.map(item => [`${item.role}|${item.tag}`, item])).values()
    ).sort((a, b) => {
      const roleDiff = roleOrder[a.role] - roleOrder[b.role];
      if (roleDiff) return roleDiff;
      return a.tag.localeCompare(b.tag, "ko");
    })
  };
}

function buildSearchIndex() {
  return walk(docsDir).sort().map(filePath => {
    const text = fs.readFileSync(filePath, "utf8");
    const visibleParts = parseVisibleParts(text);

    return {
      title: parseTitle(text, filePath),
      path: makeRoute(filePath),
      type: getDocType(filePath),
      segments: visibleParts.segments,
      tags: visibleParts.tags
    };
  });
}

const searchIndex = buildSearchIndex();
const output = `// This file is generated by scripts/generate-search-index.js.\n` +
  `// Do not edit it manually. Regenerate after adding or renaming md files.\n` +
  `window.searchIndex = ${JSON.stringify(searchIndex, null, 2)};\n`;

fs.writeFileSync(outputFile, output);
console.log(`Generated ${path.relative(rootDir, outputFile)} with ${searchIndex.length} documents.`);
